#!/usr/bin/env bash
set -euo pipefail

DATA_DIR="/data"
MARIADB_DIR="${DATA_DIR}/mariadb"
STORAGE_DIR="${DATA_DIR}/storage"
CONFIG_DIR="${DATA_DIR}/config"
ENV_FILE="${CONFIG_DIR}/.env"

mkdir -p "${MARIADB_DIR}" "${STORAGE_DIR}" "${CONFIG_DIR}" /run/mysqld
chown -R mysql:mysql "${MARIADB_DIR}" /run/mysqld
chown -R lizzart:lizzart "${STORAGE_DIR}" "${CONFIG_DIR}"

gen_hex() {
	bun -e "console.log(require('node:crypto').randomBytes(${1:-32}).toString('hex'))"
}

# Bootstrap persistent secrets & credentials on first start
if [ ! -f "${ENV_FILE}" ]; then
	echo "[Lizzart All-in-One] Primeira inicialização: gerando credenciais seguras em ${ENV_FILE}..."
	INIT_DB_PASS="${DB_PASSWORD:-$(gen_hex 24)}"
	INIT_MASTER_KEY="${APP_MASTER_KEY:-$(gen_hex 48)}"
	INIT_JWT_SECRET="${JWT_SECRET:-$(gen_hex 48)}"

	cat > "${ENV_FILE}" <<EOF
# Auto-generated by Lizzart Explorer All-in-One container
DB_HOST=127.0.0.1
DB_PORT=3306
DB_USER=${DB_USER:-lizzart}
DB_PASSWORD=${INIT_DB_PASS}
DB_NAME=${DB_NAME:-lizzart_explorer}
STORAGE_ROOT=${STORAGE_DIR}
APP_MASTER_KEY=${INIT_MASTER_KEY}
JWT_SECRET=${INIT_JWT_SECRET}
SESSION_TTL_DAYS=${SESSION_TTL_DAYS:-7}
EOF
	chmod 600 "${ENV_FILE}"
	chown lizzart:lizzart "${ENV_FILE}"
fi

# Load persisted configuration (without clobbering explicit runtime PORT/ORIGIN/FORCE_HTTPS)
SAVED_PORT="${PORT:-}"
SAVED_ORIGIN="${ORIGIN:-}"
SAVED_FORCE_HTTPS="${FORCE_HTTPS:-}"
SAVED_PERF="${PERFORMANCE_MODE:-}"

set -a
# shellcheck disable=SC1090
source "${ENV_FILE}"
set +a

export DB_HOST="${DB_HOST:-127.0.0.1}"
export DB_PORT="${DB_PORT:-3306}"
export DB_USER="${DB_USER:-lizzart}"
export DB_NAME="${DB_NAME:-lizzart_explorer}"
export STORAGE_ROOT="${STORAGE_ROOT:-${STORAGE_DIR}}"
export CONFIG_DIR="${CONFIG_DIR}"
export ENV_FILE_PATH="${ENV_FILE}"
export HOST="0.0.0.0"
export PORT="${SAVED_PORT:-${PORT:-3000}}"
export BODY_SIZE_LIMIT="Infinity"
export NODE_ENV="production"
[ -n "${SAVED_ORIGIN}" ] && export ORIGIN="${SAVED_ORIGIN}"
[ -n "${SAVED_FORCE_HTTPS}" ] && export FORCE_HTTPS="${SAVED_FORCE_HTTPS}"
[ -n "${SAVED_PERF}" ] && export PERFORMANCE_MODE="${SAVED_PERF}"

# Initialize MariaDB system tables if datadir is empty
if [ ! -d "${MARIADB_DIR}/mysql" ]; then
	echo "[Lizzart All-in-One] Inicializando banco de dados MariaDB em ${MARIADB_DIR}..."
	mariadb-install-db \
		--user=mysql \
		--datadir="${MARIADB_DIR}" \
		--auth-root-authentication-method=socket \
		--skip-test-db >/dev/null
	chown -R mysql:mysql "${MARIADB_DIR}"
fi

echo "[Lizzart All-in-One] Iniciando MariaDB (127.0.0.1:3306)..."
mariadbd \
	--user=mysql \
	--datadir="${MARIADB_DIR}" \
	--bind-address=127.0.0.1 \
	--port=3306 \
	--socket=/run/mysqld/mysqld.sock &
DB_PID=$!

# Wait for MariaDB readiness
DB_READY=0
for _ in $(seq 1 60); do
	if mariadb-admin --socket=/run/mysqld/mysqld.sock ping --silent >/dev/null 2>&1; then
		DB_READY=1
		break
	fi
	if ! kill -0 "${DB_PID}" 2>/dev/null; then
		echo "[Lizzart All-in-One] ERRO: MariaDB encerrou inesperadamente durante a inicialização." >&2
		exit 1
	fi
	sleep 0.5
done

if [ "${DB_READY}" -ne 1 ]; then
	echo "[Lizzart All-in-One] ERRO: Timeout aguardando MariaDB." >&2
	exit 1
fi

# Provision app database & hardened local-only MariaDB user idempotently
SAFE_DB="${DB_NAME//\`/}"
SAFE_USER="${DB_USER//\'/}"
SAFE_PASS="${DB_PASSWORD//\'/\'\'}"

mariadb --socket=/run/mysqld/mysqld.sock <<-EOSQL
	CREATE DATABASE IF NOT EXISTS \`${SAFE_DB}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
	CREATE USER IF NOT EXISTS '${SAFE_USER}'@'127.0.0.1' IDENTIFIED BY '${SAFE_PASS}';
	ALTER USER '${SAFE_USER}'@'127.0.0.1' IDENTIFIED BY '${SAFE_PASS}';
	CREATE USER IF NOT EXISTS '${SAFE_USER}'@'localhost' IDENTIFIED BY '${SAFE_PASS}';
	ALTER USER '${SAFE_USER}'@'localhost' IDENTIFIED BY '${SAFE_PASS}';
	GRANT ALL PRIVILEGES ON \`${SAFE_DB}\`.* TO '${SAFE_USER}'@'127.0.0.1';
	GRANT ALL PRIVILEGES ON \`${SAFE_DB}\`.* TO '${SAFE_USER}'@'localhost';
	DELETE FROM mysql.user WHERE User='';
	FLUSH PRIVILEGES;
EOSQL

echo "[Lizzart All-in-One] MariaDB pronto! Iniciando Lizzart Explorer na porta ${PORT}..."
gosu lizzart bun /app/build/index.js &
APP_PID=$!

shutdown_all() {
	echo "[Lizzart All-in-One] Encerramento gracioso solicitado..."
	if kill -0 "${APP_PID}" 2>/dev/null; then
		kill -TERM "${APP_PID}" 2>/dev/null || true
		wait "${APP_PID}" 2>/dev/null || true
	fi
	if kill -0 "${DB_PID}" 2>/dev/null; then
		mariadb-admin --socket=/run/mysqld/mysqld.sock shutdown >/dev/null 2>&1 || kill -TERM "${DB_PID}" 2>/dev/null || true
		wait "${DB_PID}" 2>/dev/null || true
	fi
	echo "[Lizzart All-in-One] Aplicação e MariaDB encerrados com segurança."
	exit 0
}

trap shutdown_all SIGTERM SIGINT SIGQUIT

# Supervise both MariaDB and App: if either dies unexpectedly, cleanly stop the other
while true; do
	if ! kill -0 "${APP_PID}" 2>/dev/null; then
		wait "${APP_PID}" || APP_CODE=$?
		echo "[Lizzart All-in-One] Aplicação encerrou (code=${APP_CODE:-0}). Desligando MariaDB com segurança..." >&2
		mariadb-admin --socket=/run/mysqld/mysqld.sock shutdown >/dev/null 2>&1 || kill -TERM "${DB_PID}" 2>/dev/null || true
		wait "${DB_PID}" 2>/dev/null || true
		exit "${APP_CODE:-1}"
	fi
	if ! kill -0 "${DB_PID}" 2>/dev/null; then
		echo "[Lizzart All-in-One] MariaDB encerrou inesperadamente. Parando aplicação..." >&2
		kill -TERM "${APP_PID}" 2>/dev/null || true
		wait "${APP_PID}" 2>/dev/null || true
		exit 1
	fi
	sleep 2
done
